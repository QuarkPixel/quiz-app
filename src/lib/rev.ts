/**
 * 修订戳：让**并发更新可排序**的那个原语。
 *
 * ── 为什么需要它 ────────────────────────────────────────────────────────────
 *
 * 两台设备各自改同一张卡（手机复习了、电脑把它推到更高档位），同步时必须有依据
 * 判断"谁更晚"。以前没有这个依据，代码只好拿 `level` 当替身——可 `level` 既不是
 * 时钟（复习不一定让它变大），也不单调（答「忘记」会把它降下来）。于是
 * 「本地复习过、云端档位更高」时云端赢，**把云端那条过期的 `nextDue` 一起带回来**，
 * 刚复习完的卡立刻又变回「待复习」。这是同一族 bug 反复出现的根因。
 *
 * ── 为什么是逻辑计数，不是墙上时钟 ──────────────────────────────────────────
 *
 * 早先这里是 `max(Date.now(), previous + 1)`。那让 `rev` 变成"写入这台机器的时钟"：
 * 手机比电脑快几秒，手机写出的每个戳就**永远**比电脑大——电脑每次同步都算出
 * "云端更新"，于是单设备（严格说：单设备 + 一只偏快的表）也会把云端那份写回本地。
 * 戳要表达的是**因果顺序**（"我是在看到你之后才改的"），不是"几点几分"。
 *
 * 所以现在是纯计数器：`nextRev(previous) = previous + 1`。
 *
 * ── 老数据怎么办 ────────────────────────────────────────────────────────────
 *
 * 老版本把毫秒时间戳直接写进了 `rev`，那些值大约在 1.7e12。新写入从
 * `REV_COUNTER_EPOCH + 1` 起算（远在任何毫秒时间戳之上、仍在安全整数范围内），
 * 于是**任何新写入都晚于任何老记录**，不需要迁移、也不会被老数据反压。
 * 两台设备都升级之后，计数在同一区间里逐个递增。
 *
 * ── 规矩 ────────────────────────────────────────────────────────────────────
 *
 * - 戳由**本机写入时**盖（唯一收口在 `MemorySession.writeProgress` 等处）；
 * - 从云端拉回来 / 合并出来的那份**原样保留、绝不重盖**——否则两台设备各盖各的，
 *   同样的内容会算出不同的状态，永远收敛不了；
 * - 没有这个字段 = `0` = 「早于任何带戳的改动」，老数据靠这条平滑迁移。
 */

/** 一条进度没带戳时的取值：早于任何带戳的改动。 */
export const NO_REV = 0;

/**
 * 逻辑计数的起点：在所有"毫秒时间戳"之上。
 *
 * 取 4e12（约公元 2096 年）是为了给老数据留出确定的次序——它一定小于这个数，
 * 所以升级后的第一次写入必然胜出。`Number.MAX_SAFE_INTEGER` 是 9e15，按每次
 * 写入 +1 算，余量足够。
 */
export const REV_COUNTER_EPOCH = 4_000_000_000_000;

/**
 * 下一次写入该用的戳。
 *
 * `previous` 要传**本机见过的同一条记录的最大戳**（本地那份与即将写入的那份取大），
 * 这样本机的新写入一定大于见过的所有旧戳。
 */
export function nextRev(previous: number = NO_REV): number {
  const base =
    typeof previous === "number" && Number.isFinite(previous) && previous > 0
      ? Math.floor(previous)
      : NO_REV;
  return Math.max(base + 1, REV_COUNTER_EPOCH + 1);
}

/** 读一条记录的戳；没有就是 `NO_REV`。 */
export function revOf(entry: { rev?: unknown } | undefined | null): number {
  const value = entry?.rev;
  return typeof value === "number" && Number.isFinite(value) && value > 0
    ? Math.floor(value)
    : NO_REV;
}
